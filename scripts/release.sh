#!/bin/bash
# Publishes the current main commit as a GitHub release. Run with:
#   bash scripts/release.sh
#
# The version comes from the VERSION file, so bump and commit it first. Refuses
# unless you're on main with a clean tree that matches origin/main and VERSION
# isn't already released. It never commits or pushes: gh creates the tag on
# GitHub at that exact commit. Everything is built and zipped before you're
# asked to confirm.
set -euo pipefail
cd "$(dirname "$0")/.."

die() { echo "!! $*" >&2; exit 1; }

[ $# -eq 0 ] || die "takes no arguments; the version comes from the VERSION file"
VERSION="$(tr -d '[:space:]' < VERSION)"
echo "$VERSION" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$' || die "VERSION is '$VERSION'; it must look like 1.2.3, with no leading v"
TAG="v$VERSION"
ZIP="dist/ActivityMonitor-$VERSION.zip"

echo "==> preflight"
command -v gh >/dev/null       || die "gh is not installed:  brew install gh"
gh auth status >/dev/null 2>&1 || die "gh is not logged in:  gh auth login"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
[ "$BRANCH" = "main" ] || die "on branch '$BRANCH'; releases are cut from main"
[ -z "$(git status --porcelain)" ] || die "uncommitted changes; commit or discard them first"
git fetch --quiet origin main
[ "$(git rev-parse HEAD)" = "$(git rev-parse origin/main)" ] \
  || die "main and origin/main differ; push (or pull) first"
[ -z "$(git ls-remote --tags origin "refs/tags/$TAG")" ] \
  || die "$TAG is already released; bump VERSION, commit, and push"
COMMIT="$(git rev-parse HEAD)"

# Ad-hoc signed: the local dev certificate means nothing on anyone else's Mac.
# Into dist/ so this never replaces the build/ copy you're running.
echo "==> building"
AM_UNIVERSAL=1 AM_SIGN_IDENTITY="-" AM_APP_DIR=dist bash scripts/build.sh

echo "==> packaging $ZIP"
rm -f "$ZIP"
ditto -c -k --keepParent dist/ActivityMonitor.app "$ZIP"
lipo -info dist/ActivityMonitor.app/Contents/MacOS/ActivityMonitor

cat <<SUMMARY

------------------------------------------------------------
Ready to publish $TAG
  commit   ${COMMIT:0:10} ($(git log -1 --format=%s))
  repo     $(gh repo view --json nameWithOwner -q .nameWithOwner)
  asset    $ZIP ($(du -h "$ZIP" | cut -f1))
  notes    generated by GitHub from commits since the last release
------------------------------------------------------------
SUMMARY

read -r -p "Publish? [y/N] " reply
[ "$reply" = "y" ] || [ "$reply" = "Y" ] || die "aborted; nothing was published"

gh release create "$TAG" "$ZIP" --target "$COMMIT" --title "Activity Monitor $VERSION" --generate-notes
git fetch --quiet --tags origin

echo
echo "Published: $(gh release view "$TAG" --json url -q .url)"
